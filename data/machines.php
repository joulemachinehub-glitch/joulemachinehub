function getCategoryUrl($categoryName) {
    global $categoryMap;
    foreach ($categoryMap as $slug => $cat) {
        if (strtolower(trim($cat['name'])) === strtolower(trim($categoryName))) {
            return 'category/' . $slug;
        }
    }
    $clean = strtolower(preg_replace('/[^a-zA-Z0-9]+/', '-', trim($categoryName)));
    $clean = trim($clean, '-');
    return 'category/used-' . $clean;
}

function getCategoryBySlug($slug) {
    global $categoryMap;
    $s = strtolower(trim($slug));
    if (isset($categoryMap[$s])) return $categoryMap[$s];
    foreach ($categoryMap as $k => $cat) {
        if (strtolower($cat['name']) === $s || $k === $s) return $cat;
        if (preg_replace('/^used-/', '', $k) === preg_replace('/^used-/', '', $s)) return $cat;
    }
    return null;
}

function getMachineUrl($machine) {
    if (isset($machine['slug']) && !empty($machine['slug'])) {
        return 'product/' . $machine['slug'];
    }
    return 'machine-details.php?id=' . urlencode($machine['id'] ?? '1');
}

function findMachineBySlugOrId($slugOrId) {
    global $machines;
    $list = $GLOBALS['machines'] ?? $machines ?? [];
    if (empty($slugOrId)) return null;

    $s = trim($slugOrId, '/');
    if (str_starts_with($s, 'product/')) $s = substr($s, 8);
    if (str_starts_with($s, 'machine/')) $s = substr($s, 8);

    // 1. Direct slug, id, or item_no match
    foreach ($list as $idx => $m) {
        if ((isset($m['slug']) && $m['slug'] === $s) || 
            (isset($m['id']) && (string)$m['id'] === (string)$s) ||
            (isset($m['item_no']) && (string)$m['item_no'] === (string)$s)) {
            return $m;
        }
    }

    // 2. Numeric 1-based index fallback (e.g. 1 -> 1st machine, 11 -> 11th machine)
    if (is_numeric($s)) {
        $idx = (int)$s - 1;
        if (isset($list[$idx])) {
            return $list[$idx];
        }
    }

    // 3. Match without 'used-' prefix or partial keyword slug (for non-numeric strings)
    $stripped = preg_replace('/^used-/', '', $s);
    foreach ($list as $m) {
        $mStripped = preg_replace('/^used-/', '', $m['slug'] ?? '');
        if ($mStripped === $stripped || str_contains($m['slug'], $stripped) || str_contains($stripped, $mStripped)) {
            return $m;
        }
    }

    return null;
}

