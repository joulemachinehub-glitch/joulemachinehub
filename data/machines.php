function getCountryUrl($country) {
    return 'country/' . strtolower(preg_replace('/[^a-zA-Z0-9]+/', '-', trim($country)));
}

function getCityUrl($city) {
    return 'city/' . strtolower(preg_replace('/[^a-zA-Z0-9]+/', '-', trim($city)));
}

function getCountryHub($param) {
    global $countryHubs;
    if (empty($param)) return $countryHubs['Japan'];
    
    $cleanParam = strtolower(preg_replace('/[^a-zA-Z0-9]+/', '', $param));
    
    foreach ($countryHubs as $k => $hub) {
        $cleanK = strtolower(preg_replace('/[^a-zA-Z0-9]+/', '', $k));
        $cleanName = strtolower(preg_replace('/[^a-zA-Z0-9]+/', '', $hub['name'] ?? ''));
        $cleanCode = strtolower($hub['code'] ?? '');
        
        if ($cleanK === $cleanParam || $cleanName === $cleanParam || $cleanCode === $cleanParam) {
            return $hub;
        }
    }
    return $countryHubs['Japan'];
}

function getCityData($param) {
    global $cityHubs;
    $default = $cityHubs['Nagoya'];
    if (empty($param)) return $default;
    
    $cleanParam = strtolower(preg_replace('/[^a-zA-Z0-9]+/', '', $param));
    
    if (isset($cityHubs[$param])) return $cityHubs[$param];
    foreach ($cityHubs as $k => $c) {
        $cleanK = strtolower(preg_replace('/[^a-zA-Z0-9]+/', '', $k));
        $cleanName = strtolower(preg_replace('/[^a-zA-Z0-9]+/', '', $c['name'] ?? ''));
        if ($cleanK === $cleanParam || $cleanName === $cleanParam) {
            return $c;
        }
    }
    return $default;
}

function getUserDetectedCurrency() {
    if (!empty($_COOKIE['jmh_currency'])) {
        $c = strtoupper(trim($_COOKIE['jmh_currency']));
        if (in_array($c, ['INR', 'USD', 'EUR'])) return $c;
    }
    $country = '';
    if (!empty($_SERVER['HTTP_CF_IPCOUNTRY'])) {
        $country = strtoupper(trim($_SERVER['HTTP_CF_IPCOUNTRY']));
    } elseif (!empty($_SERVER['GEOIP_COUNTRY_CODE'])) {
        $country = strtoupper(trim($_SERVER['GEOIP_COUNTRY_CODE']));
    } elseif (!empty($_SERVER['HTTP_X_COUNTRY_CODE'])) {
        $country = strtoupper(trim($_SERVER['HTTP_X_COUNTRY_CODE']));
    } elseif (!empty($_SERVER['HTTP_ACCEPT_LANGUAGE'])) {
        if (preg_match('/-(IN|in)\b/', $_SERVER['HTTP_ACCEPT_LANGUAGE'])) {
            $country = 'IN';
        } elseif (preg_match('/-(DE|FR|IT|ES|NL|CH|AT|BE|SE|NO|DK|PL|CZ|PT|GR|FI|IE|RO|HU|SK)\b/i', $_SERVER['HTTP_ACCEPT_LANGUAGE'])) {
            $country = 'DE';
        }
    }
    
    // 1. Indian visitors: Show INR
    if ($country === 'IN') {
        return 'INR';
    }
    
    // 2. European visitors: Show EUR
    $eurCountries = [
        'DE', 'FR', 'IT', 'ES', 'NL', 'BE', 'AT', 'CH', 'IE', 'PT', 
        'GR', 'FI', 'SE', 'NO', 'DK', 'PL', 'CZ', 'RO', 'HU', 'SK',
        'EE', 'LV', 'LT', 'SI', 'BG', 'HR', 'CY', 'LU', 'MT'
    ];
    if (in_array($country, $eurCountries)) {
        return 'EUR';
    }
    
    // 3. Relevant countries (US, Canada, Asia, Middle East, Global): Show USD
    // If country is empty and language indicates India, default to INR; otherwise international default is USD
    if (empty($country) && !empty($_SERVER['HTTP_ACCEPT_LANGUAGE']) && str_contains(strtolower($_SERVER['HTTP_ACCEPT_LANGUAGE']), 'en-in')) {
        return 'INR';
    }

    return !empty($country) ? 'USD' : 'INR';
}

function formatMachinePrice($machine, $currency = null) {
    $priceInr = floatval($machine['price'] ?? 0);
    $priceUsd = floatval($machine['price_usd'] ?? ($priceInr > 0 ? $priceInr / 85 : 0));
    
    if ($priceInr <= 0 && $priceUsd <= 0) {
        return 'Price on Request';
    }

    if ($currency === null) {
        $currency = getUserDetectedCurrency();
    }
    $currency = strtoupper(trim($currency));
    
    if ($currency === 'INR') {
        if ($priceInr >= 10000000) {
            return '₹' . number_format($priceInr / 10000000, 2) . ' Crore';
        } elseif ($priceInr >= 100000) {
            return '₹' . number_format($priceInr / 100000, 2) . ' Lakhs';
        } else {
            return '₹' . number_format($priceInr);
        }
    } elseif ($currency === 'USD') {
        return '$' . number_format($priceUsd) . ' USD';
    } elseif ($currency === 'EUR') {
        $eur = round($priceUsd * 0.92);
        return '€' . number_format($eur) . ' EUR';
    } elseif ($currency === 'JPY') {
        $jpy = round($priceUsd * 155);
        return '¥' . number_format($jpy) . ' JPY';
    }
    
    return $machine['value_raw'] ?? ('$' . number_format($priceUsd) . ' USD');
}

/**
 * Format machine location without country duplication
 * e.g., "Direct Plant Floor • Como Industrial Textile Cluster, Italy"
 */
function formatMachineLocation($machine) {
    $loc = trim($machine['location'] ?? '');
    $country = trim($machine['country'] ?? '');
    $city = trim($machine['city'] ?? '');
    
    if (empty($loc)) {
        if (!empty($city) && !empty($country)) {
            return $city . ', ' . $country;
        }
        return $city ?: ($country ?: 'Direct Plant Floor');
    }
    
    // Clean up any double country in $loc (e.g. "Cluster, Italy, Italy")
    if (!empty($country)) {
        $loc = preg_replace('/[,\s•]+\s*' . preg_quote($country, '/') . '\s*,\s*' . preg_quote($country, '/') . '$/i', ', ' . $country, $loc);
        if (preg_match('/[,\s•]\s*' . preg_quote($country, '/') . '\s*$/i', $loc) || stripos($loc, $country) !== false) {
            return $loc;
        }
        return $loc . ', ' . $country;
    }
    return $loc;
}
