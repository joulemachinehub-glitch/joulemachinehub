// 3. Ensure 'id' exists, title prefix, category normalization, and root-relative image paths across all machine records
foreach ($machines as $idx => &$m) {
    if (empty($m['id'])) {
        $m['id'] = (string)($m['product_ref'] ?? $m['item_no'] ?? ($idx + 1));
    }
    if (!empty($m['title'])) {
        // Clean any duplicated or chained prefixes e.g. "Used / Used / Old / Imported"
        $cleaned = preg_replace('/^(\s*[\/\-]\s*|\s*(Used|Second Hand|Old|Imported)\s*)+/i', '', $m['title']);
        $m['title'] = 'Used ' . trim($cleaned);
    }
    // Normalize Category: Merge 'Cold Header / Bolt Former' into 'Cold Formers & Headers'
    if (!empty($m['category'])) {
        $cleanCat = strtolower(trim($m['category']));
        if ($cleanCat === 'cold header / bolt former' || ($cleanCat !== 'cold formers & headers' && stripos($cleanCat, 'cold header') !== false)) {
            $m['category'] = 'Cold Formers & Headers';
        }
    }
    // Calculate price fallbacks if either price or price_usd is missing
    $pInr = floatval($m['price'] ?? 0);
    $pUsd = floatval($m['price_usd'] ?? 0);
    if ($pInr <= 0 && $pUsd > 0) {
        $m['price'] = round($pUsd * 85);
    } elseif ($pUsd <= 0 && $pInr > 0) {
        $m['price_usd'] = round($pInr / 85);
    }
    if (empty($m['price_display']) && ($m['price'] ?? 0) > 0) {
        $m['price_display'] = '$' . number_format($m['price_usd']) . ' USD (₹' . number_format($m['price'] / 100000, 2) . ' Lakhs)';
    }
    if (!empty($m['images']) && is_array($m['images'])) {
        foreach ($m['images'] as &$img) {
            $img = '/' . ltrim($img, '/');
        }
        unset($img);
    }
}
unset($m);

